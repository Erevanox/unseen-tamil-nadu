// ============================================================================
// TRANSLATION ENGINE — Runtime Language Switcher
// ============================================================================

let currentLanguage = localStorage.getItem('utn-lang') || 'en';

export function getCurrentLanguage() {
  return currentLanguage;
}

export function setLanguage(lang) {
  currentLanguage = lang;
  localStorage.setItem('utn-lang', lang);
}

/**
 * Get a translated string by key.
 * Supports placeholder replacement: t('key', value1, value2)
 * Placeholders are {0}, {1}, etc.
 */
export function t(key, ...args) {
  const dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS.en;
  let text = dict[key] || TRANSLATIONS.en[key] || key;
  args.forEach((arg, i) => {
    text = text.replace(`{${i}}`, arg);
  });
  return text;
}

/**
 * Apply translations to all elements with data-i18n attribute.
 * Scans the DOM and replaces textContent.
 */
export function applyStaticTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translated = t(key);
    if (translated !== key) {
      el.textContent = translated;
    }
  });

  // Also translate elements with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const translated = t(key);
    if (translated !== key) {
      el.placeholder = translated;
    }
  });

  // Also translate elements with data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const translated = t(key);
    if (translated !== key) {
      el.title = translated;
    }
  });

  // Update page title
  if (currentLanguage === 'ta') {
    document.title = 'அறியப்படாத தமிழ்நாடு — புத்திசாலி பயண திட்டமிடுபவர்';
  } else {
    document.title = 'UNSEEN TAMIL NADU — Smart Travel Planner';
  }

  // Update HTML lang attribute
  document.documentElement.lang = currentLanguage === 'ta' ? 'ta' : 'en';
}
